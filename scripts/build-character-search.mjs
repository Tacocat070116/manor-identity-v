import fs from 'node:fs';
import assert from 'node:assert/strict';

const read=path=>JSON.parse(fs.readFileSync(path,'utf8'));
const metadata=read('research/search/characters.json');
const characters=read('dist/data.json').characters;
assert.deepEqual(Object.keys(metadata.characters).sort(),characters.map(c=>c.id).sort());
const data={};
for(const c of characters){
 const source=metadata.characters[c.id];
 assert.equal(source.name,c.name);
 assert.ok(source.aliases.length&&source.sources.length,c.id+' search sources');
 for(const date of [source.releaseDate,...(source.releaseWindow||[])].filter(Boolean)){
  assert.match(date,/^\d{4}-\d{2}-\d{2}$/);
  assert.equal(new Date(date).toISOString().slice(0,10),date);
  assert.ok(date<=metadata.checkedAt);
 }
 assert.ok(source.releaseDate||source.releaseWindow?.length===2);
 data[c.id]={aliases:[...new Set(source.aliases)],releaseDate:source.releaseDate};
 if(source.releaseWindow)data[c.id].releaseWindow=source.releaseWindow;
}
fs.writeFileSync('dist/character-search-data.js','// Generated by scripts/build-character-search.mjs; edit research/search/characters.json.\nexport const characterSearchData='+JSON.stringify(data,null,1)+';\n');
console.log(`Search metadata: ${characters.length} characters, ${Object.values(data).reduce((n,c)=>n+c.aliases.length,0)} aliases`);
